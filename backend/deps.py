# ── In-memory sliding-window rate limiter ───────────────────────────────────
# Suitable for single-process deployments.  Replace with a Redis-backed
# implementation (e.g. slowapi + redis) for multi-process/multi-replica setups.

class _SlidingWindow:
    def __init__(self, limit: int, window_seconds: int):
        self._limit = limit
        self._window = window_seconds
        self._buckets: dict[str, list[float]] = defaultdict(list)
        self._lock = asyncio.Lock()

    async def is_allowed(self, key: str) -> bool:
        """Returns True if the request is within the rate limit, False otherwise."""
        now = time.monotonic()
        cutoff = now - self._window
        async with self._lock:
            ts = [t for t in self._buckets[key] if t > cutoff]
            if len(ts) >= self._limit:
                self._buckets[key] = ts
                return False
            ts.append(now)
            self._buckets[key] = ts
            return True


# 10 auth attempts per IP per 15 minutes (login + forgot-password)
login_limiter = _SlidingWindow(limit=10, window_seconds=900)
# 5 signups per IP per hour
signup_limiter = _SlidingWindow(limit=5, window_seconds=3600)
# 60 bets per user-id per minute
bet_limiter = _SlidingWindow(limit=60, window_seconds=60)
# 5 daily-claim attempts per user-id per minute (the DB is the real guard)
claim_limiter = _SlidingWindow(limit=5, window_seconds=60)
# 12 agent-authored table messages per minute. House banter is generated by
# trusted server policy and does not use this external-agent limit.
agent_chat_limiter = _SlidingWindow(limit=12, window_seconds=60)


# ── Database indexes ─────────────────────────────────────────────────────────

async def ensure_database_indexes() -> None:
    """Create all idempotency and lookup indexes at startup."""
    index_specs = [
        # Users
        (db.users, "id",       "user_id_unique",       True),
        (db.users, "email",    "user_email_unique",     True),
        (db.users, "username", "user_username_unique",  True),
        # Agents
        (db.agents, "id",  "agent_id_unique", True),
        # Wallets
        (db.wallets, "id",      "wallet_id_unique",      True),
        (db.wallets, "user_id", "wallet_user_id_unique", True),
        # Games
        (db.games, "id", "game_id_unique", True),
        # Bets
        (db.bets, "id",             "bet_id_unique",            True),
        (db.tournament_bets, "id",  "tournament_bet_id_unique", True),
        # Transactions
        (db.transactions, "id", "transaction_id_unique", True),
        # Sweepstakes
        (db.sweepstakes_profiles, "user_id", "sweepstakes_profile_user_id_unique", True),
        # Private tournament workspaces
        (db.table_pilot_workspaces, "user_id", "table_pilot_user_unique", True),
    ]
    for collection, field, name, unique in index_specs:
        await collection.create_index(field, unique=unique, name=name)
    await db.crypto_deposits.create_index("id", unique=True, name="crypto_deposit_id_unique")
    await db.crypto_deposits.create_index(
        [("crypto_type", 1), ("tx_hash", 1)],
        unique=True,
        name="crypto_transaction_claim_unique",
    )
    await db.crypto_redemptions.create_index("id", unique=True, name="crypto_redemption_id_unique")
    await db.crypto_redemptions.create_index(
        [("user_id", 1), ("idempotency_key", 1)],
        unique=True,
        name="crypto_redemption_user_idempotency_unique",
    )
    await db.table_chat_messages.create_index(
        "id", unique=True, name="table_chat_message_id_unique"
    )
    await db.table_chat_messages.create_index(
        "action_id", unique=True, sparse=True,
        name="table_chat_action_id_unique",
    )
    await db.table_chat_messages.create_index(
        [("table_id", 1), ("timestamp", -1)],
        unique=False,
        name="table_chat_history_lookup",
    )
    await db.crypto_redemptions.create_index(
        "payout_tx_hash",
        unique=True,
        sparse=True,
        name="crypto_redemption_payout_tx_hash_unique",
    )
    for coin in ("btc", "ltc", "eth"):
        await db.wallets.create_index(
            f"crypto_addresses.{coin}",
            unique=True,
            sparse=True,
            name=f"wallet_{coin}_deposit_address_unique",
        )


# ── Auth helpers ─────────────────────────────────────────────────────────────

def create_token(user_id: str, username: str, role: str = "human"):
    return jwt.encode(
        {"user_id": user_id, "username": username, "role": role,
         "exp": datetime.now(timezone.utc).timestamp() + 604800},
        JWT_SECRET, algorithm="HS256"
    )


async def get_current_user(credentials: HTTPAuthorizationCredentials = Depends(security)):
    if not credentials:
        raise HTTPException(status_code=401, detail="Not authenticated")
    return await get_user_from_token(credentials.credentials)


async def get_user_from_token(token: str):
    try:
        payload = jwt.decode(token, JWT_SECRET, algorithms=["HS256"])
        user = await db.users.find_one({"id": payload["user_id"]}, {"_id": 0})
        if not user:
            raise HTTPException(status_code=401, detail="User not found")
        return user
    except jwt.ExpiredSignatureError:
        raise HTTPException(status_code=401, detail="Token expired")
    except Exception:
        raise HTTPException(status_code=401, detail="Invalid token")


async def require_human(user=Depends(get_current_user)):
    if user.get("role") != "human":
        raise HTTPException(status_code=403, detail="Human spectator account required")
    return user


async def require_agent(user=Depends(get_current_user)):
    if user.get("role") != "agent":
        raise HTTPException(status_code=403, detail="OpenClaw agent account required")
    return user


def sanitize_game_for_response(game, show_cards=False):
    g = deepcopy({k: v for k, v in game.items() if k not in ('_id', 'deck')})
    show = show_cards or g.get('phase') in ('showdown', 'complete')
    if not show:
        for p in g.get('players', []):
            p['hole_cards'] = [None, None]
    phase_display = {
        'preflop_betting': 'preflop', 'flop_deal': 'flop',
        'flop_betting': 'flop', 'turn_deal': 'turn',
        'turn_betting': 'turn', 'river_deal': 'river',
        'river_betting': 'river',
    }
    g['display_phase'] = phase_display.get(g.get('phase'), g.get('phase'))
    g['is_betting'] = g.get('phase', '').endswith('_betting')
    return g
